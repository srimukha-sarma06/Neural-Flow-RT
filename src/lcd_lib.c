    lcd_draw_string("0", cfg->x_offset - 30, cfg->y_offset + cfg->plot_height - 4, 0xFFFFFF, scale);

    // Value Range labels (Colorbar)
    uint16_t text_x = cfg->x_offset + cfg->plot_width + 50;

